import 'dotenv/config';
import express from 'express';
import http from 'http';
import mongoose from 'mongoose';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import { Server } from 'socket.io';
import authRoutes from './routes/auth.js';
import goodsRoutes from './routes/goods.js';
import shipmentRoutes from './routes/shipments.js';
import deviceRoutes from './routes/devices.js';
import iotRoutes from './routes/iot.js';
import readingRoutes from './routes/readings.js';
import alertRoutes from './routes/alerts.js';
import analyticsRoutes from './routes/analytics.js';

const app=express(), server=http.createServer(app);
export const io=new Server(server,{cors:{origin:process.env.CLIENT_ORIGIN||'http://localhost:5173',credentials:true}});
app.use(helmet()); app.use(cors({origin:process.env.CLIENT_ORIGIN||'http://localhost:5173'}));
app.use(express.json({limit:'1mb'})); app.use(morgan('dev'));
app.use('/api',rateLimit({windowMs:60_000,max:300}));
app.get('/api/health',(_,res)=>res.json({ok:true,service:'supply-chain-api'}));
app.use('/api/auth',authRoutes); app.use('/api/goods',goodsRoutes);
app.use('/api/shipments',shipmentRoutes); app.use('/api/devices',deviceRoutes);
app.use('/api/iot',iotRoutes); app.use('/api/readings',readingRoutes);
app.use('/api/alerts',alertRoutes); app.use('/api/analytics',analyticsRoutes);
app.use((req,res)=>res.status(404).json({message:'Route not found'}));
app.use((err,req,res,next)=>{console.error(err);res.status(err.status||500).json({message:err.message||'Server error'});});
const port=process.env.PORT||5000;
mongoose.connect(process.env.MONGO_URI).then(()=>server.listen(port,()=>console.log(`API listening on ${port}`))).catch(e=>{console.error('Mongo connection failed',e);process.exit(1);});
